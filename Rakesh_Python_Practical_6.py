import pandas as pd
df = pd.read_csv('HR_Employee_AnalysisReady (2).csv')
print('Data loaded successfully')
print(df.shape)

print(df['Salary'].describe())

print(df['Training_Hours'].describe())

print(df['Department'].value_counts())

print(df['Location'].value_counts(normalize=True).round(2))

print(df[['Training_Hours','Performance_Rating']].corr().round(2))

print(df[['Experience_Years','Salary']].corr().round(2))

print(pd.crosstab(df['Department'],df['Attrition']))

print(pd.crosstab(df['Location'],df['Attrition'],normalize='index').round(2))

print(df.groupby('Department').agg(
    Avg_Salary=('Salary','mean'),
    Avg_Rating=('Performance_Rating','mean')
).round(2))

from numpy import mean
print(df.groupby('Location').agg(
    Avg_Training=('Training_Hours','mean'),
    Avg_Absence=('Absence_Days','mean')
).round(2))